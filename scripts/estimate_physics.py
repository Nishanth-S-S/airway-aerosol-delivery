#!/usr/bin/env python3
"""Derive / justify the main modelling choices from the geometry and config.

    python scripts/estimate_physics.py

Writes results/tables/flow_regime.csv, results/tables/particle_physics.csv and
docs/MODEL_DECISIONS.md (the document cited by config/experiment.yaml).
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib.breathing import LPM_TO_M3S, peak_flow  # noqa: E402
from lib.common import ROOT, df_to_markdown, load_config  # noqa: E402

KB = 1.380649e-23


def cunningham(d, lam):
    kn = 2 * lam / d
    return 1 + kn * (1.257 + 0.4 * math.exp(-1.1 / kn))


def main():
    cfg = load_config()
    g, air, b, pcfg = cfg["geometry"], cfg["air"], cfg["breathing"], cfg["particles"]
    nu, mu, rho_a = air["kinematic_viscosity"], air["dynamic_viscosity"], air["density"]
    q_mean = b["mean_flow_L_per_min"] * LPM_TO_M3S
    q_peak = max(peak_flow(cfg, w) for w in b["waveforms"])
    T = b["inhalation_duration_s"]

    rows = []
    # assume an even split for the estimate; the narrowed branch takes less, so this is conservative for the throat
    sections = [
        ("parent airway", g["parent_diameter_mm"], 1.0),
        ("daughter branch (healthy)", g["daughter_diameter_mm"], 0.5),
        ("N20 throat (4.8 mm)", 4.8, 0.5),
        ("N40 throat (3.6 mm)", 3.6, 0.5),
    ]
    for name, dmm, frac in sections:
        d = dmm * 1e-3
        A = math.pi * d * d / 4
        for lab, q in (("mean", q_mean), ("peak", q_peak)):
            U = frac * q / A
            rows.append({"section": name, "flow": lab, "diameter_mm": dmm, "Q_L_per_min": round(frac * q / LPM_TO_M3S, 3),
                         "mean_velocity_m_s": round(U, 3), "Re": round(U * d / nu, 0)})
    fr = pd.DataFrame(rows)
    (ROOT / "results" / "tables").mkdir(parents=True, exist_ok=True)
    fr.to_csv(ROOT / "results" / "tables" / "flow_regime.csv", index=False)
    re_max = fr.Re.max()
    # Womersley: treat one inhalation as half of a 2T-period cycle
    omega = 2 * math.pi / (2 * T)
    wo = (g["parent_diameter_mm"] / 2e3) * math.sqrt(omega / nu)
    re_parent_mean = fr[(fr.section == "parent airway") & (fr.flow == "mean")].Re.iloc[0]
    le = 0.05 * re_parent_mean * g["parent_diameter_mm"]
    # Dean number in the daughters (approx. curvature from the 30 deg bend, R ~ 3 D)
    re_d = fr[(fr.section == "daughter branch (healthy)") & (fr.flow == "peak")].Re.iloc[0]

    prow = []
    lam = air["mean_free_path"]
    U_ref = fr[(fr.section == "daughter branch (healthy)") & (fr.flow == "mean")].mean_velocity_m_s.iloc[0]
    for dum in pcfg["diameters_um"]:
        d = dum * 1e-6
        cc = cunningham(d, lam)
        tau0 = pcfg["density"] * d * d / (18 * mu)
        tau = tau0 * cc
        vs = tau * 9.81
        D = KB * air["temperature_K"] * cc / (3 * math.pi * mu * d)
        x_brown = math.sqrt(2 * D * (T + b["post_inhalation_s"]))
        stk = tau * U_ref / (g["daughter_diameter_mm"] * 1e-3)
        stk_throat = tau * fr[(fr.section == "N40 throat (3.6 mm)") & (fr.flow == "peak")].mean_velocity_m_s.iloc[0] / 3.6e-3
        mass = pcfg["density"] * math.pi * d ** 3 / 6
        prow.append({"diameter_um": dum, "particle_mass_kg": mass, "cunningham_Cc": round(cc, 4),
                     "slip_effect_percent": round(100 * (cc - 1), 1), "relaxation_time_s": tau,
                     "settling_velocity_mm_s": round(vs * 1e3, 4),
                     "settling_distance_in_3s_mm": round(vs * 3e3, 3),
                     "brownian_D_m2_s": D, "brownian_rms_displacement_um": round(x_brown * 1e6, 2),
                     "Stokes_daughter_mean": round(stk, 5), "Stokes_N40_throat_peak": round(stk_throat, 5),
                     "physical_particles_per_ng": 1e-12 / mass})
    pp = pd.DataFrame(prow)
    pp.to_csv(ROOT / "results" / "tables" / "particle_physics.csv", index=False)

    p1 = pp[pp.diameter_um == min(pcfg["diameters_um"])].iloc[0]
    md = f"""# Model decisions (derived from config + geometry)

Generated by `scripts/estimate_physics.py`. Re-run it after changing `config/experiment.yaml`.
Status tags used in the config: **[DERIVED]**, **[PROVISIONAL]**, **[CHOICE]**.

## 1. Flow regime → laminar, transient, incompressible  [DERIVED]

Mean parent flow {b['mean_flow_L_per_min']} L/min; highest waveform peak {q_peak / LPM_TO_M3S:.2f} L/min
(Beta(2,5) and Beta(5,2) have the same peak). Air ν = {nu:g} m²/s.

{df_to_markdown(fr)}

* The largest Reynolds number anywhere (peak flow through the 3.6 mm N40 throat, assuming an
  even split) is **≈ {re_max:.0f}**, well below the ~2000–2300 transition range for pipe flow. The parent
  airway runs at Re ≈ {re_parent_mean:.0f} on average.
* **Decision: laminar flow, no turbulence model.** A RANS model at Re < 1000 would add artificial viscosity.
  Caveat (PROVISIONAL): the jet leaving a 64 %-area stenosis can become unsteady/transitional at a lower Re
  than a straight pipe. The transient laminar solver resolves such unsteadiness directly if the mesh is
  fine enough; the mesh-independence study (validation/04) checks this for the N40 case.
* Womersley number α = R√(ω/ν) ≈ **{wo:.2f}** (one 2 s inhalation treated as half of a 4 s cycle):
  the flow is close to quasi-steady, but a transient solver is still used because the waveforms and the
  zero-flow settling period are explicitly time-dependent.
* Solver: **pimpleFoam** (transient, incompressible, PIMPLE), adaptive time step (max Courant in config).
* Entrance length for the parent tube ≈ 0.05·Re·D ≈ {le:.0f} mm > 40 mm, so the flow does not become fully
  developed in the parent tube on its own. The inlet therefore uses a **parabolic (fully developed)
  profile** by default [PROVISIONAL], representing an upstream airway. `plug` is selectable in config.

## 2. Outlet boundary condition  [PROVISIONAL]

Both outlets: static pressure p = 0, `inletOutlet` velocity. With equal pressure the flow split is decided by
the geometry (the narrowed branch receives less air). This is the simplest unbiased choice, but real
downstream lung resistance would change the split. Validation #9 (`validation/09_outlet_bc_sensitivity`)
re-runs the baseline with (a) a fixed 50/50 flow split and (b) added equal downstream resistance.

## 3. Mesh  [PROVISIONAL]

snappyHexMesh on a uniform background block mesh, surface refinement levels from config, near-wall layers.
`coarse / medium / fine` levels are defined in config and compared in validation/04.

## 4. Particles

{df_to_markdown(pp[['diameter_um', 'cunningham_Cc', 'slip_effect_percent', 'relaxation_time_s', 'settling_velocity_mm_s', 'settling_distance_in_3s_mm', 'brownian_rms_displacement_um', 'Stokes_daughter_mean', 'Stokes_N40_throat_peak']])}

* **One-way coupling** [CHOICE/DERIVED]: aerosol mass loading is tiny (introduced mass {pcfg['introduced_mass_kg']:g} kg
  in {q_mean * T * 1e6:.0f} mL of air ⇒ volume fraction ~10⁻⁸), so particles cannot change the airflow.
* **Drag + gravity** (Schiller–Naumann sphere drag, gravity {pcfg['gravity']} m/s²). Gravity direction is
  [PROVISIONAL]: an upright person inhales downward, i.e. along +Z of this model.
* **Cunningham slip** — for {p1.diameter_um:.0f} µm, C_c = {p1.cunningham_Cc:.3f}: the particle relaxation time and
  settling velocity are **{p1.slip_effect_percent:.0f} % larger** than without slip. That is not negligible for
  the 1 µm case, so the slip correction is applied when `cunningham_slip: true`. OpenFOAM's
  sphere drag has no slip term, so it is applied **exactly** by giving the parcels an effective density
  ρ_eff = ρ_p·C_c (the drag-only equation of motion depends on ρ_p/C_c only through τ = ρ_p d² C_c / 18µ,
  and the settling velocity τg is reproduced too; buoyancy ρ_air/ρ_p ≈ 0.1 % is neglected). Aerosol **mass**
  is always computed with the true density ρ_p.
* **Brownian diffusion — not included** [DERIVED]. Even for 1 µm the RMS Brownian displacement over the
  whole 3 s simulation is ≈ {p1.brownian_rms_displacement_um:.0f} µm, versus a 3000 µm branch radius; the particle
  Péclet number is ~10⁸. Brownian deposition only matters for particles below ~0.1–0.2 µm. Can be revisited
  in validation if sub-micron sizes are added.
* Wall contact: **stick** (the deposited parcel is removed and its mass recorded with its position).
* Initial velocity: parcels start with the **local mean air velocity at the inlet at the release time**. Their
  relaxation time is ≤ {pp.relaxation_time_s.max() * 1e3:.2f} ms, so any slip vanishes within < 0.1 mm of travel.

## 5. Equal introduced aerosol mass  [CHOICE]

Every case introduces the same aerosol mass M = {pcfg['introduced_mass_kg']:g} kg, regardless of diameter or
release strategy. Each computational parcel represents n_p identical physical particles:

    m_particle = ρ_p · π d³ / 6
    n_p (physical particles per parcel) = M / (N_parcels · m_particle)

with N_parcels = {pcfg['parcels_per_case']} parcels per case. A 1 µm parcel therefore represents 125× more physical
particles than a 5 µm parcel, but every case carries the same total mass. With flow-proportional release
(`release_rate_mode: flow_proportional`) parcels are released in proportion to the instantaneous inlet flow, so the
aerosol is uniformly mixed into the inspired-volume window F₀–F₁. `scripts/generate_particle_cases.py` stores n_p and
the release schedule for every case in `cases/particles/<id>/case_meta.json`.
"""
    (ROOT / "docs" / "MODEL_DECISIONS.md").write_text(md)
    print(fr.to_string(index=False))
    print(pp[["diameter_um", "cunningham_Cc", "relaxation_time_s", "brownian_rms_displacement_um", "Stokes_N40_throat_peak"]].to_string(index=False))
    print(f"Womersley {wo:.2f}; max Re {re_max:.0f}; wrote docs/MODEL_DECISIONS.md")


if __name__ == "__main__":
    main()
