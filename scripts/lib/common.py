"""Shared helpers: project paths, config loading, run-status table, logging."""
from __future__ import annotations

import csv
import datetime as _dt
import os
import subprocess
import sys
import threading
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CONFIG_PATH = ROOT / "config" / "experiment.yaml"
STATUS_CSV = ROOT / "results" / "run_status.csv"
STATUS_COLUMNS = [
    "case_id", "case_type", "geometry", "waveform", "particle_size_um", "release_strategy",
    "mesh_status", "solver_status", "particle_status", "qa_status", "notes", "updated",
]


def load_config() -> dict:
    with open(CONFIG_PATH) as fh:
        return yaml.safe_load(fh)


def rel(p: Path) -> str:
    try:
        return str(Path(p).resolve().relative_to(ROOT))
    except ValueError:
        return str(p)


# ----------------------------------------------------------------- status table
def read_status() -> dict[str, dict]:
    rows: dict[str, dict] = {}
    if STATUS_CSV.exists():
        with open(STATUS_CSV, newline="") as fh:
            for r in csv.DictReader(fh):
                rows[r["case_id"]] = {c: r.get(c, "") for c in STATUS_COLUMNS}
    return rows


_STATUS_LOCK = threading.Lock()


def update_status(case_id: str, **fields) -> None:
    """Create/update one row of results/run_status.csv (machine readable). Thread-safe."""
    with _STATUS_LOCK:
        _update_status(case_id, **fields)


def _update_status(case_id: str, **fields) -> None:
    rows = read_status()
    row = rows.get(case_id, {c: "" for c in STATUS_COLUMNS})
    row["case_id"] = case_id
    for k, v in fields.items():
        if k not in STATUS_COLUMNS:
            raise KeyError(f"unknown status column {k}")
        row[k] = "" if v is None else str(v)
    row["updated"] = _dt.datetime.now().isoformat(timespec="seconds")
    rows[case_id] = row
    STATUS_CSV.parent.mkdir(parents=True, exist_ok=True)
    with open(STATUS_CSV, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=STATUS_COLUMNS)
        w.writeheader()
        for r in sorted(rows.values(), key=lambda r: (r["case_type"], r["case_id"])):
            w.writerow(r)


# ----------------------------------------------------------------- OpenFOAM runner
def foam_cmd(cfg: dict, case_dir: Path, command: str) -> list[str]:
    """Build a command line that runs `command` inside `case_dir` with OpenFOAM loaded.

    runner=docker : official OpenCFD image, project mounted at /work
    runner=native : assumes OpenFOAM is already sourced in your shell
    """
    of = cfg["openfoam"]
    case_dir = Path(case_dir).resolve()
    if of["runner"] == "docker":
        inner = f"/work/{case_dir.relative_to(ROOT).as_posix()}"
        script = (f"source {of['bashrc']} >/dev/null 2>&1; "
                  f"export OMPI_ALLOW_RUN_AS_ROOT=1 OMPI_ALLOW_RUN_AS_ROOT_CONFIRM=1; "
                  f"cd '{inner}' && {command}")
        # cloud execution only (unset on the Mac, so behaviour there is unchanged):
        #   AIRWAY_DOCKER_ARGS   extra docker-run options, e.g. "--cpuset-cpus=8-15" to pin a case to its cores
        #   AIRWAY_DOCKER_IMAGE  image pinned by digest (same solver build as the Mac image)
        extra = os.environ.get("AIRWAY_DOCKER_ARGS", "").split()
        image = os.environ.get("AIRWAY_DOCKER_IMAGE") or of["docker_image"]
        return ["docker", "run", "--rm", "--shm-size=1g", *extra,
                "-v", f"{ROOT}:/work", "-w", inner,
                "--entrypoint", "/bin/bash", image, "-c", script]
    return ["bash", "-c", f"cd '{case_dir}' && {command}"]


def run_foam(cfg: dict, case_dir: Path, command: str, log_name: str, timeout: int | None = None) -> int:
    """Run an OpenFOAM command, tee output to <case>/logs/<log_name>.log. Returns exit code."""
    case_dir = Path(case_dir)
    logdir = case_dir / "logs"
    logdir.mkdir(exist_ok=True)
    log = logdir / f"{log_name}.log"
    print(f"    $ {command}   (log: {rel(log)})", flush=True)
    with open(log, "w") as fh:
        proc = subprocess.run(foam_cmd(cfg, case_dir, command), stdout=fh,
                              stderr=subprocess.STDOUT, timeout=timeout)
    return proc.returncode


def die(msg: str, code: int = 1):
    print(f"\nERROR: {msg}\n", file=sys.stderr)
    sys.exit(code)


def foam_header(cls: str, obj: str, location: str | None = None) -> str:
    loc = f'    location    "{location}";\n' if location else ""
    return ("/*--------------------------------*- C++ -*----------------------------------*\\\n"
            "  Generated by airway-aerosol-delivery scripts - edit config/experiment.yaml\n"
            "\\*---------------------------------------------------------------------------*/\n"
            "FoamFile\n{\n    version     2.0;\n    format      ascii;\n"
            f"    class       {cls};\n{loc}    object      {obj};\n}}\n\n")


def df_to_markdown(df) -> str:
    """Markdown table without the optional `tabulate` dependency."""
    def fmt(v):
        if isinstance(v, float):
            return f"{v:.4g}"
        return str(v)
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(fmt(r[c]) for c in cols) + " |")
    return "\n".join(out)


def geometry_files(cfg: dict, key: str, version: str | None = None) -> dict:
    """Source STL (mm), patch STL (m) and file suffix for a geometry version."""
    version = version or cfg["geometry"].get("version", "v001")
    gdir = ROOT / "geometry" / key
    if version == "v001":
        return {"version": version, "source": gdir / "airway_clean.stl", "patches": gdir / "airway_patches_m.stl", "suffix": ""}
    return {"version": version, "source": gdir / f"airway_{version}.stl",
            "patches": gdir / f"airway_patches_m_{version}.stl", "suffix": f"_{version}"}
